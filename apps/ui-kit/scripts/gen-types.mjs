// Generates TypeScript types for the UI from the contract JSON Schemas.
//
//   npm run gen:types               # regenerate runtime schemas with cargo, then the TS
//   npm run gen:types -- --skip-cargo   # only re-run json-schema-to-typescript
//
// Inputs:
//   ../../schemas/*.json      data-file schemas (owned by the integration lead, never edited here)
//   schemas/runtime/*.json    runtime types (SimEvent, VehicleState, ...), written by
//                             tools/gen-runtime-schemas from wp_contracts
// Output:
//   src/generated/contracts.ts (committed, so consumers do not need cargo)
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, "..");
const repo = resolve(pkg, "../..");
const toolDir = join(pkg, "tools/gen-runtime-schemas");
const runtimeDir = join(pkg, "schemas/runtime");

if (!process.argv.includes("--skip-cargo")) {
  // Same dependency versions as the main workspace.
  copyFileSync(join(repo, "Cargo.lock"), join(toolDir, "Cargo.lock"));
  execFileSync("cargo", ["run", "--quiet", "--manifest-path", join(toolDir, "Cargo.toml")], {
    stdio: "inherit",
    env: { ...process.env, CARGO_TARGET_DIR: join(repo, "target/ui-tools") },
  });
}

/** schemars emits draft 2020-12 `prefixItems` tuples; json-schema-to-typescript wants draft-07. */
function normalize(node) {
  if (Array.isArray(node)) return node.map(normalize);
  if (node && typeof node === "object") {
    // A `$ref` with sibling keys (usually `description`) makes json-schema-to-typescript emit
    // numbered aliases (EntityId1, EntityId2...). The referenced type carries its own docs.
    if (typeof node.$ref === "string") return { $ref: node.$ref };
    const out = {};
    for (const [k, v] of Object.entries(node)) {
      if (k === "prefixItems") {
        out.items = normalize(v);
        out.additionalItems = false;
      } else if (k === "items" && node.prefixItems) {
        // `items: false` after prefixItems means "no extra items": already covered.
      } else if (k === "format" || k === "$schema") {
        // Drop numeric formats (uint16, float...) to keep the output clean.
      } else {
        out[k] = normalize(v);
      }
    }
    return out;
  }
  return node;
}

const files = [
  ...readdirSync(join(repo, "schemas"))
    .filter((f) => f.endsWith(".schema.json"))
    .map((f) => join(repo, "schemas", f)),
  ...readdirSync(runtimeDir)
    .filter((f) => f.endsWith(".schema.json"))
    .map((f) => join(runtimeDir, f)),
].sort();

const defs = {};
const roots = {};
for (const file of files) {
  const schema = normalize(JSON.parse(readFileSync(file, "utf8")));
  const { $defs = {}, title, ...body } = schema;
  if (!title) throw new Error(`${file}: schema has no title`);
  for (const [name, def] of Object.entries($defs)) {
    if (defs[name] && JSON.stringify(defs[name]) !== JSON.stringify(def)) {
      throw new Error(`$defs/${name} differs between schemas (last: ${file})`);
    }
    defs[name] = def;
  }
  roots[title] = { title, ...body };
}
for (const [title, body] of Object.entries(roots)) {
  if (defs[title] && JSON.stringify(defs[title]) !== JSON.stringify(body)) {
    // A root type that also appears as a nested def (e.g. DamageMode): keep the nested copy.
    continue;
  }
  defs[title] = body;
}
for (const [name, def] of Object.entries(defs)) {
  if (!def.title) def.title = name;
}

const combined = {
  title: "WpContractsBundle",
  description: "Every contract type the UI reads. Not a real message; only used for codegen.",
  type: "object",
  properties: Object.fromEntries(Object.keys(roots).map((t) => [t, { $ref: `#/$defs/${t}` }])),
  additionalProperties: false,
  $defs: defs,
};

const ts = await compile(combined, "WpContractsBundle", {
  bannerComment: [
    "/* eslint-disable */",
    "/**",
    " * GENERATED by apps/ui-kit/scripts/gen-types.mjs from wp_contracts JSON Schemas.",
    " * Do not edit by hand: run `npm run gen:types`.",
    " */",
  ].join("\n"),
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  style: { singleQuote: false },
});

mkdirSync(join(pkg, "src/generated"), { recursive: true });
writeFileSync(join(pkg, "src/generated/contracts.ts"), ts);
console.log(`wrote src/generated/contracts.ts (${Object.keys(roots).length} root types, ${Object.keys(defs).length} definitions)`);
