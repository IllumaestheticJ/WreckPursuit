//! The render list (`data/panels/RENDER_LIST.md`): every car's personality, silhouette,
//! signature details, lighting and palette (from its style sheet) next to what its generated
//! mesh actually contains (lamps, bolt-on parts, glass, wheels, triangle count). Written by
//! `gen-car-mesh`; `cargo test -p car-assets` fails when it is stale.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use wp_contracts::LoadedCar;

use crate::mesh::{CarMesh, MaterialSlot, PartKind};
use crate::style::CarStyle;

/// Where the render list lives (repo-relative).
pub const RENDER_LIST_PATH: &str = "data/panels/RENDER_LIST.md";

/// One car's entry.
pub struct Entry<'a> {
    /// Loaded car (definition).
    pub car: &'a LoadedCar,
    /// Its style sheet.
    pub style: &'a CarStyle,
    /// Its generated mesh.
    pub mesh: &'a CarMesh,
}

fn group_of(kind: PartKind, material: MaterialSlot) -> &'static str {
    match (kind, material) {
        (PartKind::Panel, _) => "Body panels",
        (PartKind::Glass, _) => "Glass",
        (PartKind::Light, _) => "Lamps",
        (PartKind::Mirror, _) => "Mirrors",
        (PartKind::Detail, _) => "Bolt-on details",
        (PartKind::Body, _) => "Structure & trim",
        (PartKind::Interior, _) => "Interior",
        (PartKind::Tire | PartKind::Rim, _) => "Wheels",
    }
}

/// Collapse `_l`/`_r` (and `fl`/`fr`, `rl`/`rr`) pairs into one name with a ×2 count.
fn collapse(names: &[&str]) -> String {
    let mut counts: BTreeMap<String, usize> = BTreeMap::new();
    for n in names {
        let base = if let Some(s) = n.strip_suffix("_l").or_else(|| n.strip_suffix("_r")) {
            format!("{s}_l/r")
        } else {
            n.replace("_fl", "_f*")
                .replace("_fr", "_f*")
                .replace("_rl", "_r*")
                .replace("_rr", "_r*")
        };
        *counts.entry(base).or_insert(0) += 1;
    }
    counts
        .into_iter()
        .map(|(n, c)| {
            if c > 1 && !n.ends_with("_l/r") {
                format!("`{n}` ×{c}")
            } else {
                format!("`{n}`")
            }
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// Render the whole list.
pub fn render(entries: &[Entry]) -> String {
    let mut s = String::new();
    s.push_str("# Car render list\n\n");
    s.push_str(
        "*Generated by `cargo run -p car-assets --bin gen-car-mesh` from `data/panels/styles/*.toml` \
         and the generated meshes; do not edit by hand.*\n\n",
    );
    s.push_str(
        "Every vehicle's personality and visual brief (style sheet) next to what its mesh \
         actually carries. Shapes are anchored to the damage lattice (doors, hood, trunk and \
         glass sit exactly on their lattice regions so they dent, swing and fall off \
         correctly); everything between the anchors — nose, tail, flares, creases, bulges, \
         beds and boxes — and every lamp and bolt-on part comes from the style sheet.\n\n",
    );
    s.push_str("| Vehicle | Class | Tagline | Palette | Tris |\n|---|---|---|---|---|\n");
    for e in entries {
        let _ = writeln!(
            s,
            "| [{}](#{}) | {:?} | {} | `{}` / `{}` | {} |",
            e.car.def.display_name,
            e.car.def.id,
            e.car.def.class,
            e.style.identity.tagline,
            e.style.palette.base,
            e.style.palette.accent,
            e.mesh.tri_count
        );
    }
    s.push('\n');
    for e in entries {
        let d = &e.car.def;
        let st = &e.style;
        let _ = writeln!(s, "## {} (`{}`) {{#{}}}\n", d.display_name, d.id, d.id);
        let _ = writeln!(
            s,
            "*{}* — {:?}, {}\n",
            st.identity.tagline, d.class, d.analog_of
        );
        let _ = writeln!(s, "**Personality.** {}\n", st.identity.personality);
        if !st.identity.silhouette.is_empty() {
            let _ = writeln!(s, "**Silhouette.** {}\n", st.identity.silhouette);
        }
        if !st.identity.lighting.is_empty() {
            let _ = writeln!(s, "**Lighting.** {}\n", st.identity.lighting);
        }
        if !st.identity.signatures.is_empty() {
            s.push_str("**Signature details.**\n");
            for sig in &st.identity.signatures {
                let _ = writeln!(s, "- {sig}");
            }
            s.push('\n');
        }
        let alts = if st.palette.alts.is_empty() {
            String::new()
        } else {
            format!(
                "; alternates {}",
                st.palette
                    .alts
                    .iter()
                    .map(|a| format!("`{a}`"))
                    .collect::<Vec<_>>()
                    .join(" ")
            )
        };
        let _ = writeln!(
            s,
            "**Palette.** base `{}`, accent `{}`, primer `{}`{alts}\n",
            st.palette.base, st.palette.accent, st.palette.primer
        );
        let _ = writeln!(
            s,
            "**Wheels.** {:?} rims, {:?} finish{}{}{}\n",
            st.wheels.rim,
            st.wheels.finish,
            if st.wheels.dual_rear {
                ", dual rear tires"
            } else {
                ""
            },
            if st.wheels.extra_axles.len() > 1 {
                ", tandem rear axle"
            } else {
                ""
            },
            if st.wheels.white_letters {
                ", raised white letters"
            } else {
                ""
            },
        );
        // Mesh contents by group.
        let mut groups: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
        for p in &e.mesh.parts {
            if matches!(p.kind, PartKind::Tire | PartKind::Rim) {
                continue;
            }
            groups
                .entry(group_of(p.kind, p.material))
                .or_default()
                .push(&p.name);
        }
        let wheel_parts = e
            .mesh
            .parts
            .iter()
            .filter(|p| p.kind == PartKind::Tire)
            .count();
        s.push_str("| Render group | Parts |\n|---|---|\n");
        for (g, names) in &groups {
            let _ = writeln!(s, "| {g} | {} |", collapse(names));
        }
        let _ = writeln!(s, "| Wheels | {wheel_parts} tire meshes |");
        let _ = writeln!(
            s,
            "\n{} parts, {} triangles.\n",
            e.mesh.parts.len(),
            e.mesh.tri_count
        );
    }
    s
}
