#[cfg(test)]
mod tests {
    #[test]
    fn embedded_net_data_resolves() {
        let (cars, modes) = super::embedded_data().unwrap();
        assert!(cars.contains_key("debug_sedan") && cars.contains_key("debug_coupe"));
        assert_eq!(modes.len(), 2);
    }

    #[test]
    fn client_queues_hello() {
        super::net_create("t", 0).unwrap();
        super::net_connect(0.0, "").unwrap();
        let out = super::net_take_outgoing().unwrap();
        let len = u32::from_le_bytes(out[..4].try_into().unwrap()) as usize;
        assert_eq!(out.len(), 4 + len);
        assert_eq!(out[4], 0x01, "Hello tag");
    }
}
