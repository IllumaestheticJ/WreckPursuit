//! Multiplayer client surface (added by workstream 07; self-contained so it merges cleanly
//! with workstream 04's session API). Wraps [`wp_net::client::Client`]: the page owns the
//! WebSocket, passes every received binary frame to `net_receive`, calls `net_update` once
//! per animation frame and sends what `net_take_outgoing` returns.
//!
//! | function | purpose |
//! |---|---|
//! | `net_create(name, input_source)` | new client (`input_source` 0 keyboard, 1 gamepad, 2 wheel) |
//! | `net_connect(now_ms, token)` | queue `Hello` (`token` "" or a reconnect token string) |
//! | `net_receive(bytes, now_ms)` | one received frame |
//! | `net_update(now_ms, input_json)` | predict, ping, send inputs (`VehicleInput` JSON) |
//! | `net_take_outgoing()` | frames to send: repeated `u32 LE length, bytes` |
//! | `net_render_json(now_ms)` | `[{entity, car_id, kind, own, pos, rot, speed_mps, gear, engine_rpm, health, body_size_m}]` |
//! | `net_status_json()` | phase, player, token, role, vehicle, mode, offers, orders, races, account, notices |
//! | `net_stats_json()` | RTT, mispredictions, correction size, bandwidth, hash checks |
//! | `net_captain_json()` | captain map: units, incidents, heat |
//! | `net_request_role(role, now_ms)` | 0 racer, 1 police chase, 2 captain, 3 spectator |
//! | `net_captain_order_json(json, now_ms)` | `{kind: move\|block\|pursue\|hold, units, x, y, target}` (m) |
//! | `net_race_create_json(json, now_ms)` | `{laps, checkpoints: [[x, y], …]}` (m) |
//! | `net_race_join/start/leave(race, now_ms)`, `net_race_invite(race, player, now_ms)` | lobby |
//! | `net_bye(now_ms)` | leave without a reconnect window |

use std::cell::RefCell;
use std::collections::BTreeMap;

use serde::{Deserialize, Serialize};
use wasm_bindgen::prelude::*;
use wp_contracts::{DamageMode, InputSource, LoadedCar, ModeTable, VehicleInput};
use wp_net::client::{default_damage_factory, Client, ClientConfig, Phase};
use wp_net::protocol::{role_from_u8, role_to_u8, CaptainOrder, ClientMsg, EntityKind, RaceState};

type Data = (BTreeMap<String, LoadedCar>, BTreeMap<DamageMode, ModeTable>);

/// Every embedded car and both mode tables, via [`crate::data`] (generated by `build.rs`, so
/// new cars and materials from other workstreams are picked up automatically).
pub fn embedded_data() -> Result<Data, String> {
    let mut cars = BTreeMap::new();
    for id in crate::data::car_ids() {
        let car = crate::data::load_car(&id)?;
        cars.insert(id, car);
    }
    let mut modes = BTreeMap::new();
    for mode in [DamageMode::Arcade, DamageMode::Simulation] {
        modes.insert(mode, crate::data::mode_table(mode)?);
    }
    Ok((cars, modes))
}

struct NetApp {
    client: Client,
    body_sizes: BTreeMap<String, [f32; 3]>,
}

thread_local! {
    static NET: RefCell<Option<NetApp>> = const { RefCell::new(None) };
}

fn err(e: impl std::fmt::Display) -> JsValue {
    JsValue::from_str(&format!("wp_wasm net: {e}"))
}

fn with_net<T>(f: impl FnOnce(&mut NetApp) -> Result<T, String>) -> Result<T, JsValue> {
    NET.with(|n| match n.borrow_mut().as_mut() {
        Some(app) => f(app).map_err(err),
        None => Err(err("call net_create() first")),
    })
}

fn kind_str(k: EntityKind) -> &'static str {
    match k {
        EntityKind::Racer => "racer",
        EntityKind::PoliceChase => "police",
        EntityKind::AiPolice => "ai_police",
        EntityKind::Traffic => "traffic",
    }
}

fn role_str(r: wp_contracts::Role) -> &'static str {
    match role_to_u8(r) {
        0 => "racer",
        1 => "police_chase",
        2 => "police_captain",
        _ => "spectator",
    }
}

/// Create the network client (replaces any previous one).
#[wasm_bindgen]
pub fn net_create(name: &str, input_source: u8) -> Result<(), JsValue> {
    let (cars, modes) = embedded_data().map_err(err)?;
    let body_sizes = cars
        .iter()
        .map(|(id, c)| (id.clone(), c.def.body_size_m))
        .collect();
    let input_source = match input_source {
        1 => InputSource::Gamepad,
        2 => InputSource::Wheel,
        _ => InputSource::Keyboard,
    };
    let client = Client::new(ClientConfig {
        name: name.chars().take(32).collect(),
        input_source,
        cars,
        modes,
        damage_factory: default_damage_factory,
    });
    NET.with(|n| *n.borrow_mut() = Some(NetApp { client, body_sizes }));
    Ok(())
}

/// Queue the `Hello` (call when the socket opens). `token` is "" or a reconnect token.
#[wasm_bindgen]
pub fn net_connect(now_ms: f64, token: &str) -> Result<(), JsValue> {
    let token: u64 = if token.is_empty() {
        0
    } else {
        token.parse().map_err(|_| err("bad token"))?
    };
    with_net(|n| {
        n.client.connect(now_ms, token);
        Ok(())
    })
}

/// Feed one received binary frame.
#[wasm_bindgen]
pub fn net_receive(bytes: &[u8], now_ms: f64) -> Result<(), JsValue> {
    with_net(|n| n.client.receive(bytes, now_ms).map_err(|e| e.to_string()))
}

/// Per-frame update with the local `VehicleInput` (JSON; missing fields = 0/false).
#[wasm_bindgen]
pub fn net_update(now_ms: f64, input_json: &str) -> Result<(), JsValue> {
    let input: VehicleInput = serde_json::from_str(input_json).map_err(err)?;
    with_net(|n| {
        n.client.update(now_ms, &input);
        Ok(())
    })
}

/// Frames to send, concatenated as `u32 LE length, bytes` records.
#[wasm_bindgen]
pub fn net_take_outgoing() -> Result<Vec<u8>, JsValue> {
    with_net(|n| {
        let mut out = Vec::new();
        for (_, frame) in n.client.drain_outgoing() {
            out.extend_from_slice(&(frame.len() as u32).to_le_bytes());
            out.extend_from_slice(&frame);
        }
        Ok(out)
    })
}

#[derive(Serialize)]
struct RenderEntry<'a> {
    entity: u32,
    car_id: &'a str,
    kind: &'static str,
    own: bool,
    pos: [f32; 3],
    rot: [f32; 4],
    speed_mps: f32,
    gear: i8,
    engine_rpm: f32,
    health: f32,
    body_size_m: [f32; 3],
}

/// Vehicles to draw at `now_ms` (own car predicted, others interpolated).
#[wasm_bindgen]
pub fn net_render_json(now_ms: f64) -> Result<String, JsValue> {
    with_net(|n| {
        let list = n.client.render(now_ms);
        let entries: Vec<RenderEntry> = list
            .iter()
            .map(|v| RenderEntry {
                entity: v.entity,
                car_id: &v.car_id,
                kind: kind_str(v.kind),
                own: v.own,
                pos: v.state.pos,
                rot: v.state.rot,
                speed_mps: v.state.speed_mps,
                gear: v.state.gear,
                engine_rpm: v.state.engine_rpm,
                health: v.state.health,
                body_size_m: n
                    .body_sizes
                    .get(&v.car_id)
                    .copied()
                    .unwrap_or([1.8, 4.5, 1.4]),
            })
            .collect();
        Ok(serde_json::to_string(&entries).expect("serializable"))
    })
}

#[derive(Serialize)]
struct RaceJson {
    race: u32,
    host: u32,
    state: &'static str,
    start_tick: u64,
    stake: i64,
    laps: u8,
    checkpoints: Vec<[f32; 2]>,
    members: Vec<u32>,
}

/// Session status as JSON.
#[wasm_bindgen]
pub fn net_status_json() -> Result<String, JsValue> {
    with_net(|n| {
        let c = &n.client;
        let phase = match c.phase() {
            Phase::Idle => "idle".to_string(),
            Phase::Connecting => "connecting".to_string(),
            Phase::Joined => "joined".to_string(),
            Phase::Rejected(r) => format!("rejected: {r}"),
        };
        let races: Vec<RaceJson> = c
            .races
            .values()
            .map(|r| RaceJson {
                race: r.race,
                host: r.host,
                state: match r.state {
                    RaceState::Lobby => "lobby",
                    RaceState::Countdown => "countdown",
                    RaceState::Running => "running",
                    RaceState::Finished => "finished",
                },
                start_tick: r.start_tick,
                stake: r.stake,
                laps: r.laps,
                checkpoints: r
                    .checkpoints
                    .iter()
                    .map(|p| [p[0] as f32 / 10.0, p[1] as f32 / 10.0])
                    .collect(),
                members: r.members.clone(),
            })
            .collect();
        let v = serde_json::json!({
            "phase": phase,
            "player": c.player().map(|p| p.0),
            "token": c.token().to_string(),
            "role": role_str(c.role()),
            "vehicle": c.own_vehicle().map(|e| e.0),
            "mode": match c.mode() { DamageMode::Arcade => "arcade", DamageMode::Simulation => "sim" },
            "captain_offer": c.captain_offer,
            "unit_order": c.unit_order.map(|o| serde_json::json!({
                "kind": o.kind, "x": o.x_dm as f32 / 10.0, "y": o.y_dm as f32 / 10.0, "target": o.target
            })),
            "races": races,
            "race_progress": c.race_progress.iter().map(|((r, p), cp)| serde_json::json!({"race": r, "player": p, "next": cp})).collect::<Vec<_>>(),
            "race_results": c.race_results.as_ref().map(|(race, entries)| serde_json::json!({
                "race": race,
                "entries": entries.iter().map(|e| serde_json::json!({
                    "player": e.player, "place": e.place, "time_s": e.time_ticks as f64 / 240.0, "payout": e.payout
                })).collect::<Vec<_>>()
            })),
            "invites": c.invites,
            "account": {"cash": c.account.0, "rep": c.account.1, "cop_rank": c.account.2, "bounty": c.account.3},
            "notices": c.notices,
        });
        Ok(v.to_string())
    })
}

/// Debug-overlay counters as JSON.
#[wasm_bindgen]
pub fn net_stats_json() -> Result<String, JsValue> {
    with_net(|n| {
        let s = n.client.stats();
        Ok(serde_json::json!({
            "rtt_ms": s.rtt_ms,
            "jitter_ms": s.jitter_ms,
            "reconciles": s.reconciles,
            "mispredictions": s.mispredictions,
            "last_correction_m": s.last_correction_m,
            "max_correction_m": s.max_correction_m,
            "correction_rms_m": s.correction_rms_m(),
            "prediction_resets": s.prediction_resets,
            "bps_in": s.bps_in,
            "bps_out": s.bps_out,
            "bytes_in": s.bytes_in,
            "bytes_out": s.bytes_out,
            "snapshots": s.snapshots,
            "hash_checks": s.hash_checks,
            "hash_mismatches": s.hash_mismatches,
            "resyncs": s.resyncs,
            "remotes": n.client.remotes().len(),
            "predicted_tick": n.client.predicted_tick(),
        })
        .to_string())
    })
}

/// Captain map as JSON (positions in metres, heading in radians, 0 = +Y, CCW).
#[wasm_bindgen]
pub fn net_captain_json() -> Result<String, JsValue> {
    with_net(|n| {
        let m = &n.client.captain;
        Ok(serde_json::json!({
            "tick": m.tick,
            "units": m.units.values().map(|u| serde_json::json!({
                "entity": u.entity,
                "kind": kind_str(u.kind),
                "x": u.x_dm as f32 / 10.0,
                "y": u.y_dm as f32 / 10.0,
                "heading": u.heading as f32 / 256.0 * std::f32::consts::TAU,
                "wanted": u.wanted,
                "order": u.order,
            })).collect::<Vec<_>>(),
            "incidents": m.incidents.iter().map(|i| serde_json::json!({
                "x": i.x_dm as f32 / 10.0, "y": i.y_dm as f32 / 10.0, "kind": i.kind, "age_s": i.age_s
            })).collect::<Vec<_>>(),
            "heat": m.heat.iter().map(|(x, y, h)| serde_json::json!({
                "x": *x as f32 * 100.0, "y": *y as f32 * 100.0, "size": 100.0, "heat": h
            })).collect::<Vec<_>>(),
        })
        .to_string())
    })
}

