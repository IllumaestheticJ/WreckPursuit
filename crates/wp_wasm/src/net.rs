pub fn net_request_role(role: u8, now_ms: f64) -> Result<(), JsValue> {
    let role = role_from_u8(role).map_err(err)?;
    with_net(|n| {
        n.client.request_role(role, now_ms);
        Ok(())
    })
}

#[derive(Deserialize)]
struct OrderJson {
    kind: String,
    #[serde(default)]
    units: Vec<u32>,
    #[serde(default)]
    x: f32,
    #[serde(default)]
    y: f32,
    #[serde(default)]
    target: u32,
}

/// Send a captain order (see the module table).
#[wasm_bindgen]
pub fn net_captain_order_json(json: &str, now_ms: f64) -> Result<(), JsValue> {
    let o: OrderJson = serde_json::from_str(json).map_err(err)?;
    let (x_dm, y_dm) = ((o.x * 10.0).round() as i32, (o.y * 10.0).round() as i32);
    let order = match o.kind.as_str() {
        "move" => CaptainOrder::MoveTo {
            units: o.units,
            x_dm,
            y_dm,
        },
        "block" => CaptainOrder::Block {
            units: o.units,
            x_dm,
            y_dm,
        },
        "pursue" => CaptainOrder::Pursue {
            units: o.units,
            target: o.target,
        },
        "hold" => CaptainOrder::Hold { units: o.units },
        k => return Err(err(format!("unknown order kind {k}"))),
    };
    with_net(|n| {
        n.client.captain_order(&order, now_ms);
        Ok(())
    })
}

#[derive(Deserialize)]
struct RaceCreateJson {
    laps: u8,
    checkpoints: Vec<[f32; 2]>,
}

/// Create a race from checkpoints in metres.
#[wasm_bindgen]
pub fn net_race_create_json(json: &str, now_ms: f64) -> Result<(), JsValue> {
    let r: RaceCreateJson = serde_json::from_str(json).map_err(err)?;
    let msg = ClientMsg::RaceCreate {
        laps: r.laps,
        checkpoints: r
            .checkpoints
            .iter()
            .map(|p| [(p[0] * 10.0).round() as i32, (p[1] * 10.0).round() as i32])
            .collect(),
    };
    with_net(|n| {
        n.client.send_reliable(&msg, now_ms);
        Ok(())
    })
}

fn send(msg: ClientMsg, now_ms: f64) -> Result<(), JsValue> {
    with_net(|n| {
        n.client.send_reliable(&msg, now_ms);
        Ok(())
    })
}

/// Join a race.
#[wasm_bindgen]
pub fn net_race_join(race: u32, now_ms: f64) -> Result<(), JsValue> {
    send(ClientMsg::RaceJoin { race }, now_ms)
}

